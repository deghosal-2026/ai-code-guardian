class TestHallucinatedApi:
    def test_detects_unknown_function(self):
        detections = [make_detection("src/api.py")]
        violations = hallucinated_api(detections, AI_DIFF_WITH_HALLUCINATION, "critical")
        assert len(violations) >= 1
        assert violations[0].rule_name == "hallucinated-api"
        assert "fetchDataFromInternalDB" in violations[0].pattern_found

    def test_skips_known_apis(self):
        detections = [make_detection("src/api.py")]
        violations = hallucinated_api(detections, AI_DIFF_CLEAN_APIS, "critical")
        known_names = {v.pattern_found for v in violations}
        assert "json.dumps" not in known_names
        assert "os.getenv" not in known_names

    def test_empty_detections_no_violations(self):
        violations = hallucinated_api([], AI_DIFF_WITH_HALLUCINATION, "critical")
        assert len(violations) == 0

    def test_low_confidence_skipped(self):
        detections = [make_detection("src/api.py", confidence="low")]
        violations = hallucinated_api(detections, AI_DIFF_WITH_HALLUCINATION, "critical")
        assert len(violations) == 0

    def test_skips_local_variable_methods(self):
        detections = [make_detection("src/api.py")]
        violations = hallucinated_api(detections, AI_DIFF_CLEAN_APIS, "critical")
        assert all("response.json" not in v.pattern_found for v in violations)

    def test_detects_direct_call_not_nested(self):
        direct_diff = """\
diff --git a/src/api.py b/src/api.py
index a..b 100644
--- a/src/api.py
+++ b/src/api.py
@@ -1,3 +1,7 @@
+# Generated by Copilot
+def run():
+    result = someHallucinatedApiCall()
+    return result
"""
        detections = analyze_diff(direct_diff)
        violations = hallucinated_api(detections, direct_diff, "critical")
        hallucinated_names = {v.pattern_found for v in violations}
        assert "someHallucinatedApiCall" in hallucinated_names

    def test_integration_with_real_diff(self, sample_ai_diff):
        detections = analyze_diff(sample_ai_diff)
        violations = hallucinated_api(detections, sample_ai_diff, "critical")
        known_names = {v.pattern_found for v in violations}
        assert "json.dumps" not in known_names
        assert "token.startswith" not in known_names


