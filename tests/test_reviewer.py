class TestEngine:
    def test_evaluate_runs_all_rules(self):
        detections = [make_detection("src/utils.py")]
        policy = PolicyConfig(
            version=1,
            mode="advisory",
            detection="marker",
            rules=[
                RuleConfig(name="hallucinated-api", severity="critical", enabled=True),
                RuleConfig(name="missing-error-handling", severity="high", enabled=True),
                RuleConfig(name="hardcoded-secrets", severity="critical", enabled=True),
            ],
        )
        result = evaluate(detections, policy, AI_DIFF_WITH_BARE_EXCEPT)
        assert isinstance(result, ReviewResult)
        assert result.risk_level != "low"

    def test_evaluate_skips_disabled_rules(self):
        detections = [make_detection("src/utils.py")]
        policy = PolicyConfig(
            version=1,
            mode="advisory",
            detection="marker",
            rules=[
                RuleConfig(name="hallucinated-api", severity="critical", enabled=False),
                RuleConfig(name="missing-error-handling", severity="high", enabled=False),
                RuleConfig(name="hardcoded-secrets", severity="critical", enabled=False),
            ],
        )
        result = evaluate(detections, policy, AI_DIFF_WITH_BARE_EXCEPT)
        assert len(result.violations) == 0
        assert result.risk_level == "low"

    def test_evaluate_empty_detections(self):
        policy = PolicyConfig(
            version=1,
            mode="advisory",
            detection="marker",
            rules=[
                RuleConfig(name="hallucinated-api", severity="critical", enabled=True),
            ],
        )
        result = evaluate([], policy, AI_DIFF_WITH_BARE_EXCEPT)
        assert len(result.violations) == 0
        assert result.risk_level == "low"

    def test_evaluate_unknown_rule_skipped(self):
        detections = [make_detection("src/utils.py")]
        policy = PolicyConfig(
            version=1,
            mode="advisory",
            detection="marker",
            rules=[
                RuleConfig(name="nonexistent-rule", severity="critical", enabled=True),
            ],
        )
        result = evaluate(detections, policy, AI_DIFF_WITH_BARE_EXCEPT)
        assert len(result.violations) == 0

    def test_compute_risk_level_empty(self):
        assert compute_risk_level([]) == "low"

    def test_compute_risk_level_highest_severity(self):
        v_low = Violation(rule_name="test", severity="low", file_path="f", line=1, pattern_found="", explanation="", remediation="")
        v_high = Violation(rule_name="test", severity="high", file_path="f", line=1, pattern_found="", explanation="", remediation="")
        v_critical = Violation(rule_name="test", severity="critical", file_path="f", line=1, pattern_found="", explanation="", remediation="")
        assert compute_risk_level([v_low]) == "low"
        assert compute_risk_level([v_high]) == "high"
        assert compute_risk_level([v_low, v_critical]) == "critical"
        assert compute_risk_level([v_low, v_high]) == "high"
