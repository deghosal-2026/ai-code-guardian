class TestRunDetect:
    @patch("guardian.action.GitHubClient")
    @patch("guardian.action.analyze_diff")
    @patch("guardian.action.evaluate")
    @patch("guardian.action.generate_comment")
    @patch("guardian.action.apply_risk_label")
    @patch("guardian.action.generate_check_run_output")
    @patch("guardian.action.determine_conclusion")
    @patch("guardian.action.AuditLogger")
    def test_detect_pr_flow(
        self,
        mock_audit_logger,
        mock_determine_conclusion,
        mock_generate_output,
        mock_apply_label,
        mock_generate_comment,
        mock_evaluate,
        mock_analyze_diff,
        mock_client,
    ):
        from argparse import Namespace
        from guardian.action import run_detect

        mock_client_instance = MagicMock()
        mock_client_instance.get_pr_diff.return_value = "diff --git a/f.py b/f.py\n+# Generated by Copilot\n+print('hi')"
        mock_client.return_value = mock_client_instance

        mock_analyze_diff.return_value = []
        mock_review = MagicMock()
        mock_review.violations = []
        mock_review.risk_level = "low"
        mock_review.summary = "Clean"
        mock_evaluate.return_value = mock_review
        mock_generate_comment.return_value = "comment body"
        mock_generate_output.return_value = {"title": "Review", "summary": "OK", "text": ""}
        mock_determine_conclusion.return_value = "neutral"

        args = Namespace(
            token="test-token",
            repo="owner/repo",
            pr=42,
            commit=None,
            policy="guardian-policy.yml",
            audit_dir="/tmp/test_audit",
            verbose=False,
        )

        result = run_detect(args)
        assert result == 0
        mock_client_instance.get_pr_diff.assert_called_once_with(42)
        mock_client_instance.post_comment.assert_called_once()
        mock_apply_label.assert_called_once()
        mock_client_instance.create_check_run.assert_called_once()
        mock_audit_logger.return_value.append.assert_called_once()

