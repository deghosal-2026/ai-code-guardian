class TestMultiFile:
    def test_multiple_files_detected(self):
        results = analyze_diff(CODIFF_MULTI_FILE)
        assert len(results) == 2

    def test_file_paths_correct(self):
        results = analyze_diff(CODIFF_MULTI_FILE)
        paths = {r.file_path for r in results}
        assert "src/a.py" in paths
        assert "src/b.py" in paths

    def test_tools_per_file(self):
        results = analyze_diff(CODIFF_MULTI_FILE)
        result_map = {r.file_path: r for r in results}
        assert any(m.tool == "copilot" for m in result_map["src/a.py"].matches)
        assert any(m.tool == "cursor" for m in result_map["src/b.py"].matches)


class TestDetectionResultStructure:
    def test_returns_detection_result_objects(self):
        results = analyze_diff(CODIFF_COPILOT)
        for r in results:
            assert isinstance(r, DetectionResult)

    def test_marker_match_has_expected_fields(self):
        results = analyze_diff(CODIFF_COPILOT)
        for r in results:
            for m in r.matches:
                assert isinstance(m, MarkerMatch)
                assert isinstance(m.tool, str)
                assert isinstance(m.pattern, str)
                assert isinstance(m.line, int)
                assert m.confidence in ("high", "medium")
